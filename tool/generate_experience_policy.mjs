import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const policy = JSON.parse(await readFile(new URL('shared/experience-experiments.json', root), 'utf8'));
const raw = JSON.stringify(policy);
const hash = createHash('sha256').update(raw).digest('hex');
const content = `// GENERATED by tool/generate_experience_policy.mjs; do not edit.\nconst experiencePolicyJson = r'''${raw}''';\nconst experiencePolicyHash = '${hash}';\n`;
for (const [path, output] of [
  ['lib/core/experience_policy.g.dart', content],
  ['api/src/experience-policy.g.mjs', `// GENERATED by tool/generate_experience_policy.mjs; do not edit.\nexport const experiencePolicy = ${raw};\nexport const experiencePolicyHash = '${hash}';\n`],
]) {
  const target = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw Error(`Experience policy drift: ${path}`);
  } else await writeFile(target, output);
}
